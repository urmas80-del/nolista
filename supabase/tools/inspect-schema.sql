-- NoLista: database inspection query
--
-- READ-ONLY. It changes nothing; it only reads the system catalogs.
-- Run it in: Supabase Dashboard -> SQL Editor -> New query -> paste -> Run.
-- Then export the result (Export / Download CSV) and save it as
--   supabase/schema-dump.csv   (this file is git-ignored)
--
-- Output: one row per database object (tables, constraints, indexes, views,
-- RLS policies, functions, triggers, grants, realtime tables, cron jobs).

with
tbls as (
  select c.oid, c.relname, c.relkind, c.relrowsecurity, c.relforcerowsecurity,
         c.reloptions, c.relacl
  from pg_class c
  where c.relnamespace = 'public'::regnamespace
    and c.relkind in ('r', 'p', 'v', 'm')
),
out as (
  -- 01 extensions
  select '01 extension'::text as section,
         e.extname::text as name,
         ('version ' || e.extversion || ', schema ' || e.extnamespace::regnamespace::text)::text as definition
  from pg_extension e

  union all
  -- 02 enum types
  select '02 enum',
         t.typname::text,
         'create type public.' || quote_ident(t.typname) || ' as enum ('
           || string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) || ');'
  from pg_type t
  join pg_enum e on e.enumtypid = t.oid
  where t.typnamespace = 'public'::regnamespace
  group by t.typname

  union all
  -- 03 tables (columns, defaults, RLS on/off)
  select '03 table',
         t.relname::text,
         'create table public.' || quote_ident(t.relname) || E' (\n'
           || string_agg(
                '  ' || quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
                || case when a.attidentity = 'a' then ' generated always as identity'
                        when a.attidentity = 'd' then ' generated by default as identity'
                        else '' end
                || case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
                        when d.adbin is not null then ' default ' || pg_get_expr(d.adbin, d.adrelid)
                        else '' end
                || case when a.attnotnull then ' not null' else '' end,
                E',\n' order by a.attnum)
           || E'\n);'
           || case when t.relrowsecurity then E'\n-- RLS: ENABLED' else E'\n-- RLS: DISABLED' end
           || case when t.relforcerowsecurity then ' (forced)' else '' end
  from tbls t
  join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef d on d.adrelid = t.oid and d.adnum = a.attnum
  where t.relkind in ('r', 'p')
  group by t.relname, t.relrowsecurity, t.relforcerowsecurity

  union all
  -- 04 constraints (PK, unique, FK incl. ON DELETE, check)
  select '04 constraint',
         c.conrelid::regclass::text || ' / ' || c.conname,
         'alter table ' || c.conrelid::regclass::text || ' add constraint ' || quote_ident(c.conname)
           || ' ' || pg_get_constraintdef(c.oid) || ';'
  from pg_constraint c
  where c.connamespace = 'public'::regnamespace and c.conrelid <> 0

  union all
  -- 05 indexes
  select '05 index', i.tablename || ' / ' || i.indexname, i.indexdef || ';'
  from pg_indexes i
  where i.schemaname = 'public'

  union all
  -- 06 views
  select '06 view',
         t.relname::text,
         '-- options: ' || coalesce(array_to_string(t.reloptions, ', '), '(none)') || E'\n'
           || 'create or replace view public.' || quote_ident(t.relname) || E' as\n'
           || pg_get_viewdef(t.oid, true)
  from tbls t
  where t.relkind in ('v', 'm')

  union all
  -- 07 RLS policies
  select '07 policy',
         p.tablename || ' / ' || p.policyname,
         'create policy ' || quote_ident(p.policyname) || ' on public.' || quote_ident(p.tablename)
           || ' as ' || lower(p.permissive) || ' for ' || lower(p.cmd)
           || ' to ' || array_to_string(p.roles, ', ')
           || coalesce(E'\n  using (' || p.qual || ')', '')
           || coalesce(E'\n  with check (' || p.with_check || ')', '') || ';'
  from pg_policies p
  where p.schemaname = 'public'

  union all
  -- 08 functions / RPCs (full source, incl. SECURITY DEFINER)
  select '08 function',
         p.oid::regprocedure::text,
         pg_get_functiondef(p.oid) || ';'
  from pg_proc p
  where p.pronamespace = 'public'::regnamespace
    and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend dep where dep.objid = p.oid and dep.deptype = 'e')

  union all
  -- 09 who may EXECUTE each function
  select '09 function grant',
         p.oid::regprocedure::text,
         coalesce(array_to_string(p.proacl, ', '), '(default ACL: EXECUTE granted to PUBLIC)')
  from pg_proc p
  where p.pronamespace = 'public'::regnamespace
    and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend dep where dep.objid = p.oid and dep.deptype = 'e')

  union all
  -- 10 triggers on public tables and on auth.users (e.g. "create profile on signup")
  select '10 trigger',
         tg.tgrelid::regclass::text || ' / ' || tg.tgname,
         pg_get_triggerdef(tg.oid, true) || ';'
  from pg_trigger tg
  join pg_class c on c.oid = tg.tgrelid
  where not tg.tgisinternal
    and c.relnamespace in ('public'::regnamespace, 'auth'::regnamespace)

  union all
  -- 11 table-level grants (anon / authenticated access)
  select '11 table grant',
         t.relname::text,
         coalesce(array_to_string(t.relacl, ', '), '(default ACL)')
  from tbls t

  union all
  -- 12 column-level grants (e.g. protecting profiles.is_premium)
  select '12 column grant',
         t.relname || '.' || a.attname,
         array_to_string(a.attacl, ', ')
  from tbls t
  join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
  where a.attacl is not null

  union all
  -- 13 tables published to Realtime
  select '13 realtime', pt.schemaname || '.' || pt.tablename, 'publication ' || pt.pubname
  from pg_publication_tables pt
  where pt.pubname = 'supabase_realtime'

  union all
  -- 14 pg_cron jobs (only if pg_cron is installed and readable)
  select '14 cron jobs', 'cron.job',
         query_to_xml('select jobname, schedule, command, active from cron.job', false, false, '')::text
  where coalesce(has_table_privilege(to_regclass('cron.job'), 'select'), false)
)
select section, name, definition
from out
order by section, name;
